// Timeline

E.timeline = [];
E.globalUpdaters = [];
E.chapters = [];

E.scene = (id, build, opts = {}) => {
  const s = new Scene(id, opts);
  build(s);
  const dur = opts.dur ?? s.t + (opts.tail ?? 0.3);
  E.timeline.push({ id, s, dur, opts });
  return s;
};

E.finalize = () => {
  const stage = document.getElementById('stage');
  let T = 0;
  for (const sc of E.timeline) {
    sc.start = T;
    T += sc.dur;
    stage.querySelector('#scenes').append(sc.s.root);
    if (sc.opts.chapter) E.chapters.push({ start: sc.start, ...sc.opts.chapter });
  }
  E.total = T;
  E.cues = [];
  for (const sc of E.timeline) for (const c of sc.s.cues) E.cues.push({ ...c, at: c.at + sc.start, scene: sc.id });
  E.cues.sort((a, b) => a.at - b.at);
};

E.seek = T => {
  for (const g of E.globalUpdaters) g(T);
  for (const sc of E.timeline) {
    const local = T - sc.start;
    const active = local >= -0.001 && local < sc.dur + 0.001;
    sc.s.root.style.display = active ? 'block' : 'none';
    if (active) for (const u of sc.s.updaters) u(local);
  }
};

// Make sure every glyph in every weight is loaded before we render frames.
E.preloadFonts = async () => {
  const subText = Object.values(E.LINES)
    .map(l => l.text)
    .join('');
  const text = [
    ...new Set(document.getElementById('scenes').textContent + subText + '0123456789：，。！？“”《》—…·%'),
  ].join('');
  const box = E.h('div', { style: { position: 'absolute', left: '-9999px', top: 0, visibility: 'hidden' } });
  for (const fam of ['Noto Serif SC', 'Noto Sans SC'])
    for (const w of [300, 400, 500, 600, 700, 900]) box.append(E.h('div', { style: { fontFamily: fam, fontWeight: w } }, [text]));
  document.body.append(box);
  for (const sc of E.timeline) sc.s.root.style.display = 'block';
  document.body.offsetHeight;
  await document.fonts.ready;
  await new Promise(r => setTimeout(r, 300));
  await document.fonts.ready;
  for (const sc of E.timeline) sc.s.root.style.display = 'none';
  box.remove();
};
