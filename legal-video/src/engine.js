// Deterministic, seekable motion-graphics engine.
// Every visual state is a pure function of time, so any frame can be rendered
// independently (which lets us render the film in parallel chunks).
//
// The timeline is driven by the narration: s.say(id) places a voice line at
// the scene cursor and advances the cursor by its real duration (+ pause), so
// animation can be keyed to the exact moment a word is spoken.

const E = (window.E = {});

E.W = 1920;
E.H = 1080;

E.clamp = (x, a = 0, b = 1) => Math.min(b, Math.max(a, x));
E.lerp = (a, b, x) => a + (b - a) * x;
E.prog = (t, start, dur) => (dur <= 0 ? (t >= start ? 1 : 0) : E.clamp((t - start) / dur));
E.ease = {
  lin: x => x,
  out: x => 1 - Math.pow(1 - x, 3),
  out5: x => 1 - Math.pow(1 - x, 5),
  in: x => x * x * x,
  in2: x => x * x,
  inOut: x => (x < 0.5 ? 4 * x * x * x : 1 - Math.pow(-2 * x + 2, 3) / 2),
  sine: x => -(Math.cos(Math.PI * x) - 1) / 2,
  expo: x => (x === 1 ? 1 : 1 - Math.pow(2, -10 * x)),
  back: x => {
    const c1 = 1.70158;
    const c3 = c1 + 1;
    return 1 + c3 * Math.pow(x - 1, 3) + c1 * Math.pow(x - 1, 2);
  },
  elastic: x =>
    x === 0 || x === 1 ? x : Math.pow(2, -10 * x) * Math.sin((x * 10 - 0.75) * ((2 * Math.PI) / 3)) + 1,
};
// window in/out envelope: 0 → 1 (fade in over din) … 1 → 0 (fade out over dout)
E.env = (t, a, din, b, dout) =>
  Math.min(E.ease.out(E.prog(t, a, din)), 1 - E.ease.inOut(E.prog(t, b, dout)));

E.rng = seed => {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};
E.gauss = r => {
  let u = 0;
  let v = 0;
  while (u === 0) u = r();
  while (v === 0) v = r();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
};

const SVGNS = 'http://www.w3.org/2000/svg';
E.h = (tag, attrs = {}, children = []) => {
  const el = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) {
    if (k === 'style' && typeof v === 'object') Object.assign(el.style, v);
    else if (k === 'class') el.className = v;
    else if (k === 'html') el.innerHTML = v;
    else el.setAttribute(k, v);
  }
  for (const c of [].concat(children)) el.append(c);
  return el;
};
E.s = (tag, attrs = {}, children = []) => {
  const el = document.createElementNS(SVGNS, tag);
  for (const [k, v] of Object.entries(attrs)) {
    if (k === 'style' && typeof v === 'object') Object.assign(el.style, v);
    else el.setAttribute(k, v);
  }
  for (const c of [].concat(children)) el.append(c);
  return el;
};
E.svgRoot = (w = E.W, h = E.H, attrs = {}) =>
  E.s('svg', {
    width: w,
    height: h,
    viewBox: `0 0 ${w} ${h}`,
    style: { position: 'absolute', left: 0, top: 0, overflow: 'visible' },
    ...attrs,
  });

// Inline markup: {r:红字} {g:金字} {w:亮白} {m:灰字} {b:蓝灰} {s:删除线}
E.parseMarkup = str => {
  const out = [];
  const re = /\{([rgwmbs]):([^}]*)\}/g;
  let last = 0;
  let m;
  while ((m = re.exec(str))) {
    if (m.index > last) out.push({ text: str.slice(last, m.index), cls: '' });
    out.push({ text: m[2], cls: 'mk-' + m[1] });
    last = re.lastIndex;
  }
  if (last < str.length) out.push({ text: str.slice(last), cls: '' });
  return out;
};
E.plainLen = str => E.parseMarkup(str).reduce((n, p) => n + [...p.text].length, 0);

// set transform/opacity/filter quickly
E.set = (el, { o, x = 0, y = 0, s = 1, r = 0, blur = 0, extra = '' } = {}) => {
  if (o !== undefined) el.style.opacity = o.toFixed(4);
  el.style.transform = `translate(${x.toFixed(2)}px, ${y.toFixed(2)}px) scale(${s.toFixed(4)}) rotate(${r.toFixed(3)}deg) ${extra}`;
  el.style.filter = blur > 0.05 ? `blur(${blur.toFixed(2)}px)` : 'none';
};

