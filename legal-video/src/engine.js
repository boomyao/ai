// Narration data (generated by tools/tts.py into build/data.js)

E.LINES = window.LINES || {};
E.VO = window.VO || {};
const PUNCT = /[\s，。？！；：、—…“”‘’《》（）·,.?!;:'"()]/;

// Per-character timings of a voice line's spoken text (say text, punctuation
// removed), interpolated inside each word-boundary token.
E.charTimes = id => {
  const vo = E.VO[id];
  if (!vo) throw new Error('no voice for ' + id);
  if (vo._chars) return vo._chars;
  const say = [...vo.say].filter(c => !PUNCT.test(c));
  const times = new Array(say.length).fill(null);
  let pos = 0;
  for (const [ws, we, tok] of vo.words) {
    const tchars = [...tok].filter(c => !PUNCT.test(c));
    if (!tchars.length) continue;
    // find token at or after pos
    let k = pos;
    while (k < say.length && say.slice(k, k + tchars.length).join('') !== tchars.join('')) k++;
    if (k >= say.length) continue;
    for (let i = 0; i < tchars.length; i++) {
      const a = ws + ((we - ws) * i) / tchars.length;
      const b = ws + ((we - ws) * (i + 1)) / tchars.length;
      times[k + i] = [a, b];
    }
    pos = k + tchars.length;
  }
  // fill gaps
  for (let i = 0; i < times.length; i++) {
    if (!times[i]) {
      const prev = times.slice(0, i).reverse().find(Boolean);
      const t = prev ? prev[1] : 0;
      times[i] = [t, t + 0.05];
    }
  }
  vo._chars = { chars: say, times };
  return vo._chars;
};

// Split display text and say text into punctuation-delimited segments and
// time them. Display and say text must share the same punctuation skeleton.
E.segments = id => {
  const line = E.LINES[id];
  const vo = E.VO[id];
  const splitRe = /(——|……|[，。？！；：、])/;
  const disp = line.text.split(splitRe);
  const say = vo.say.split(splitRe);
  const segs = [];
  const { times } = E.charTimes(id);
  let ci = 0;
  if (disp.length !== say.length) {
    return [{ text: line.text, start: 0, end: vo.dur, punct: '' }];
  }
  for (let i = 0; i < say.length; i += 2) {
    const sChars = [...say[i]].filter(c => !PUNCT.test(c));
    const dText = disp[i];
    const punct = disp[i + 1] || '';
    if (!sChars.length) {
      if (segs.length && punct) segs[segs.length - 1].punct += punct;
      continue;
    }
    const a = times[ci][0];
    const b = times[ci + sChars.length - 1][1];
    ci += sChars.length;
    segs.push({ text: dText, start: a, end: b, punct });
  }
  return segs;
};

