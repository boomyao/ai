// Scene builder: a cursor-based DSL. Each call schedules things at `this.t`
// (seconds from scene start) and registers an updater that maps time → DOM.

class Scene {
  constructor(id, opts = {}) {
    this.id = id;
    this.opts = opts;
    this.t = 0;
    this.updaters = [];
    this.cues = [];
    this.root = E.h('div', { class: 'scene', 'data-scene': id });
    this.cam = E.h('div', { class: 'cam' });
    this.root.append(this.cam);
    this.layer = this.cam;
  }
  add(fn) {
    this.updaters.push(fn);
    return fn;
  }
  wait(d) {
    this.t += d;
    return this;
  }
  at(t) {
    this.t = t;
    return this;
  }
  mark() {
    return this.t;
  }
  sfx(name, opts = {}) {
    this.cues.push({ type: 'sfx', name, at: opts.at ?? this.t, gain: opts.gain ?? 1, ...opts });
  }
  music(mood, opts = {}) {
    this.cues.push({ type: 'music', mood, at: opts.at ?? this.t, fade: opts.fade ?? 2, gain: opts.gain ?? 1 });
  }
  duck(amount, opts = {}) {
    // extra music level change (dB) at a moment, e.g. silence before a slam
    this.cues.push({ type: 'duck', db: amount, at: opts.at ?? this.t, ramp: opts.ramp ?? 0.3 });
  }

  // Place a narration line at the cursor. Returns a handle with absolute (scene)
  // times and a word lookup: h.w('干的') → time that substring starts.
  say(id, opts = {}) {
    const line = E.LINES[id];
    const vo = E.VO[id];
    if (!line || !vo) throw new Error('unknown line ' + id);
    const start = opts.at ?? this.t;
    const h = { id, start, dur: vo.dur, end: start + vo.dur, text: line.text };
    h.w = (sub, which = 'start') => {
      const { chars, times } = E.charTimes(id);
      const target = [...sub].filter(c => !PUNCT.test(c)).join('');
      const joined = chars.join('');
      const k = joined.indexOf(target);
      if (k < 0) throw new Error(`"${sub}" not in ${id}: ${vo.say}`);
      return start + (which === 'end' ? times[k + target.length - 1][1] : times[k][0]);
    };
    this.cues.push({ type: 'vo', id, at: start, dur: vo.dur, sub: opts.sub !== false, file: vo.file });
    if (opts.advance !== false) this.t = h.end + (opts.pause ?? line.pause ?? 0);
    this.last = h;
    return h;
  }

  el(tag, attrs, children) {
    const el = E.h(tag, attrs, children);
    (attrs?.parent || this.layer).append(el);
    return el;
  }

  // Kinetic text block. lines: string | string[]
  //   at: start time (default cursor)      until: exit time (default: +hold)
  //   anim: rise | fade | type | stamp | slam | none
  //   sync: voice handle → characters appear as they are spoken
  text(lines, opts = {}) {
    lines = [].concat(lines);
    const o = {
      cls: 'body',
      x: E.W / 2,
      y: E.H / 2,
      align: 'center',
      anim: 'rise',
      stagger: 0.035,
      charDur: 0.55,
      exitDur: 0.5,
      lineGap: null,
      parent: this.layer,
      width: null,
      style: {},
      ...opts,
    };
    const start = o.at ?? (o.sync ? o.sync.start : this.t);
    const block = E.h('div', {
      class: `tb tb-${o.cls}`,
      style: {
        left: o.x + 'px',
        top: o.y + 'px',
        textAlign: o.align,
        width: o.width ? o.width + 'px' : 'auto',
        ...o.style,
      },
    });
    const ax = o.align === 'left' ? '0%' : o.align === 'right' ? '-100%' : '-50%';
    block.style.translate = `${ax} -50%`;
    o.parent.append(block);

    const chars = [];
    let lineStart = start;
    let revealEnd = start;
    lines.forEach((line, li) => {
      const row = E.h('div', { class: 'tl' });
      block.append(row);
      let ci = 0;
      for (const part of E.parseMarkup(line)) {
        for (const ch of [...part.text]) {
          const span = E.h('span', { class: 'ch ' + part.cls });
          span.textContent = ch;
          row.append(span);
          chars.push({ el: span, at: lineStart + ci * (o.anim === 'type' ? 0.06 : o.stagger), ch });
          ci++;
        }
      }
      if (line === '') row.innerHTML = '&nbsp;';
      const len = E.plainLen(line);
      const rEnd = lineStart + len * (o.anim === 'type' ? 0.06 : o.stagger) + o.charDur;
      revealEnd = Math.max(revealEnd, rEnd);
      if (li < lines.length - 1) lineStart += o.lineGap ?? Math.max(0.35, len * 0.06);
    });
    // voice-synced reveal: map visible characters onto spoken characters
    if (o.sync) {
      const { chars: sc, times } = E.charTimes(o.sync.id);
      const vis = chars.filter(c => !PUNCT.test(c.ch));
      const visStr = vis.map(c => c.ch).join('');
      const spoken = sc.join('');
      let k = 0;
      for (let n = Math.min(4, visStr.length); n >= 1; n--) {
        const idx = spoken.indexOf(visStr.slice(0, n));
        if (idx >= 0) {
          k = idx;
          break;
        }
      }
      for (const c of vis) {
        let j = k;
        while (j < sc.length && sc[j] !== c.ch) j++;
        if (j < sc.length && j - k < 8) {
          c.at = o.sync.start + times[j][0];
          k = j + 1;
        } else {
          c.at = o.sync.start + times[Math.min(k, times.length - 1)][0];
        }
      }
      let lastAt = vis.length ? vis[0].at : start;
      for (const c of chars) {
        if (PUNCT.test(c.ch)) c.at = lastAt;
        else lastAt = c.at;
      }
      revealEnd = Math.max(...chars.map(c => c.at)) + o.charDur;
    }
    if (o.anim === 'type' && o.typeSfx !== false) {
      chars.forEach((c, i) => i % 2 === 0 && this.cues.push({ type: 'sfx', name: 'key', at: c.at, gain: 0.35, v: i }));
    }
    const until = o.until ?? (o.hold !== undefined ? revealEnd + o.hold : Infinity);
    const handle = { el: block, start, revealEnd, exitAt: until, exitDur: o.exitDur };
    handle.exit = (at, dur = o.exitDur) => {
      handle.exitAt = at;
      handle.exitDur = dur;
    };
    const anim = o.anim;
    this.add(t => {
      if (t < start - 0.01 || t > handle.exitAt + handle.exitDur + 0.01) {
        block.style.display = 'none';
        return;
      }
      block.style.display = 'block';
      for (const c of chars) {
        const p = E.prog(t, c.at, anim === 'type' ? 0.01 : o.charDur);
        if (anim === 'rise') {
          const e = E.ease.out(p);
          E.set(c.el, { o: e, y: (1 - e) * 24, blur: (1 - e) * 9 });
        } else if (anim === 'fade') {
          E.set(c.el, { o: E.ease.sine(p) });
        } else if (anim === 'type') {
          c.el.style.opacity = p > 0 ? 1 : 0;
        } else if (anim === 'stamp' || anim === 'slam') {
          const q = E.prog(t, start, anim === 'slam' ? 0.16 : 0.3);
          const e = anim === 'slam' ? E.ease.out5(q) : E.ease.back(q);
          E.set(c.el, { o: E.clamp(q * 3), s: E.lerp(anim === 'slam' ? 2.4 : 1.5, 1, e), blur: (1 - q) * 6 });
        } else {
          c.el.style.opacity = t >= c.at ? 1 : 0;
        }
      }
      const xp = E.prog(t, handle.exitAt, handle.exitDur);
      const e = E.ease.inOut(xp);
      block.style.opacity = (1 - e).toFixed(4);
      block.style.filter = e > 0.02 ? `blur(${(e * 8).toFixed(2)}px)` : 'none';
      block.style.transform = `translateY(${(-e * 12).toFixed(2)}px)`;
    });
    return handle;
  }

  // Generic element with an in/out envelope. update(t, k, h) gets scene time
  // and the envelope value.
  fx(el, { start = this.t, din = 0.6, end = Infinity, dout = 0.6, update } = {}) {
    const h = { el, start, end, dout };
    h.exit = (at, d = h.dout) => {
      h.end = at;
      h.dout = d;
    };
    this.add(t => {
      if (t < start - 0.01 || t > h.end + h.dout + 0.01) {
        el.style.visibility = 'hidden';
        return;
      }
      el.style.visibility = 'visible';
      const k = E.env(t, start, din, h.end, h.dout);
      if (update) update(t, k, h);
      else el.style.opacity = k.toFixed(4);
    });
    return h;
  }

  // Slow camera move on the whole scene layer: keyframes [[t, {x, y, s}], ...]
  camera(keys) {
    this.add(t => {
      let a = keys[0];
      let b = keys[keys.length - 1];
      for (let i = 0; i < keys.length - 1; i++) {
        if (t >= keys[i][0] && t <= keys[i + 1][0]) {
          a = keys[i];
          b = keys[i + 1];
          break;
        }
      }
      const p = a === b ? 1 : E.ease.inOut(E.prog(t, a[0], b[0] - a[0]));
      const v = k => E.lerp(a[1][k] ?? (k === 's' ? 1 : 0), b[1][k] ?? (k === 's' ? 1 : 0), p);
      const sh = this._shake ? this._shake(t) : [0, 0];
      this.cam.style.transform = `translate(${(v('x') + sh[0]).toFixed(2)}px, ${(v('y') + sh[1]).toFixed(2)}px) scale(${v('s').toFixed(4)})`;
    });
  }
}
E.Scene = Scene;

